"""
Gradient Novelty Muon optimizer.

Every proj_freq steps, compute SVD of W and cache the top-k left singular vectors
covering 50% of weight Frobenius norm. On every step, project the gradient to remove
its component along those cached vectors before adding to momentum:
    G = G - U_k @ (U_k.T @ G)

This directly attacks entropy collapse by preventing the gradient from reinforcing
the already-dominant singular directions of the weight matrix.

The SVD is amortized over proj_freq steps (default 10), so cost is low.
The projection G = G - U_k @ (U_k.T @ G) is two matmuls per param, which compiles.

Usage: drop-in replacement for MuonAdamW / DistMuonAdamW. Set gradient_novelty=True
and proj_freq=10 in the Muon param groups to enable.
"""

import torch
import torch.distributed as dist
from torch import Tensor

from nanochat.optim import (
    adamw_step_fused,
    polar_express_coeffs,
)

# -----------------------------------------------------------------------------
# Fused kernel: Muon + gradient novelty projection

@torch.compile(dynamic=False, fullgraph=True)
def gradnovelty_muon_step_fused(
    stacked_grads: Tensor,          # (K, m, n)
    stacked_params: Tensor,         # (K, m, n)
    momentum_buffer: Tensor,        # (K, m, n)
    second_momentum_buffer: Tensor, # (K, m, 1) or (K, 1, n)
    momentum_t: Tensor,
    lr_t: Tensor,
    wd_t: Tensor,
    beta2_t: Tensor,
    ns_steps: int,
    red_dim: int,
) -> None:
    """Standard Muon step (no novelty projection — that happens outside the kernel)."""

    # Nesterov momentum
    momentum = momentum_t.to(stacked_grads.dtype)
    momentum_buffer.lerp_(stacked_grads, 1 - momentum)
    g = stacked_grads.lerp_(momentum_buffer, momentum)

    # Polar express
    X = g.bfloat16()
    X = X / (X.norm(dim=(-2, -1), keepdim=True) * 1.02 + 1e-6)
    if g.size(-2) > g.size(-1):
        for a, b, c in polar_express_coeffs[:ns_steps]:
            A = X.mT @ X
            B = b * A + c * (A @ A)
            X = a * X + X @ B
    else:
        for a, b, c in polar_express_coeffs[:ns_steps]:
            A = X @ X.mT
            B = b * A + c * (A @ A)
            X = a * X + B @ X
    g = X

    # Variance reduction (NorMuon)
    beta2 = beta2_t.to(g.dtype)
    v_mean = g.float().square().mean(dim=red_dim, keepdim=True)
    red_dim_size = g.size(red_dim)
    v_norm_sq = v_mean.sum(dim=(-2, -1), keepdim=True) * red_dim_size
    v_norm = v_norm_sq.sqrt()
    second_momentum_buffer.lerp_(v_mean.to(dtype=second_momentum_buffer.dtype), 1 - beta2)
    step_size = second_momentum_buffer.clamp_min(1e-10).rsqrt()
    scaled_sq_sum = (v_mean * red_dim_size) * step_size.float().square()
    v_norm_new = scaled_sq_sum.sum(dim=(-2, -1), keepdim=True).sqrt()
    final_scale = step_size * (v_norm / v_norm_new.clamp_min(1e-10))
    g = g * final_scale.to(g.dtype)

    # Cautious weight decay + parameter update
    lr = lr_t.to(g.dtype)
    wd = wd_t.to(g.dtype)
    mask = (g * stacked_params) >= 0
    stacked_params.sub_(lr * g + lr * wd * stacked_params * mask)


def _compute_cached_basis(params, fro_frac=0.5):
    """Compute top-k left singular vectors of each param covering fro_frac of Frobenius norm.

    Returns a list of U_k tensors (one per param), where U_k has shape (m, k).
    k is chosen so that sum(S[:k]^2) >= fro_frac * sum(S^2).
    """
    basis_list = []
    for p in params:
        # SVD in float32 for stability
        U, S, Vh = torch.linalg.svd(p.data.float(), full_matrices=False)
        # Find k such that cumulative energy >= fro_frac
        s_sq = S.square()
        total_energy = s_sq.sum()
        cum_energy = s_sq.cumsum(dim=0)
        # k = first index where cumulative >= threshold, +1 for count
        threshold = fro_frac * total_energy
        k = int((cum_energy >= threshold).long().argmax().item()) + 1
        k = max(k, 1)  # at least 1
        basis_list.append(U[:, :k].to(p.dtype).contiguous())
    return basis_list


def _project_out_basis(grads, basis_list):
    """Project out the cached basis from each gradient: G = G - U_k @ (U_k.T @ G).

    This is done per-param (not stacked) because k varies across params.
    Modifies grads in-place.
    """
    for i, (grad, U_k) in enumerate(zip(grads, basis_list)):
        if U_k is not None:
            # U_k: (m, k), grad: (m, n) -> projection: (m, n)
            # (U_k.T @ G) = (k, n), U_k @ that = (m, n)
            proj = U_k @ (U_k.mT @ grad)
            grad.sub_(proj)


